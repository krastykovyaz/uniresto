export function getLanguage() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && translations[saved]) return saved;
  } catch {
    /* localStorage unavailable (private mode etc.) -- fall through to default */
  }
  return DEFAULT_LANG;
}

export function setLanguage(code) {
  try {
    localStorage.setItem(STORAGE_KEY, code);
  } catch {
    /* per-viewer convenience only; losing it silently is fine */
  }
}

export function langInfo(code) {
  return LANGUAGES.find((l) => l.code === code) || LANGUAGES[0];
}

/** Locale to hand to Intl (dates, times, language names). A language may
 * declare an `intlFallback` for browsers whose Intl data lacks it --
 * some Chromium builds ship without Luxembourgish, and German is the
 * closest widely available locale for its day/month names. */
export function intlLocale(code) {
  const info = langInfo(code);
  if (!info.intlFallback) return info.locale;
  try {
    return Intl.DateTimeFormat.supportedLocalesOf(info.locale).length ? info.locale : info.intlFallback;
  } catch {
    return info.intlFallback;
  }
}

/**
 * t(lang, "key", {name: "Salad'bar"}) -> looks up translations[lang][key],
 * falls back to English, then to the key itself so a missing string is
 * visible (not a crash). Supports {placeholder} substitution and a
 * simple "singular | plural" split on the literal count 1 vs other
 * (not full ICU plural rules -- see README.md Part 4 §-- for why that's
 * an intentional simplification for a handful of counted strings).
 */
export function t(lang, key, vars) {
  const dict = translations[lang] || translations[DEFAULT_LANG];
  let str = dict[key] ?? translations[DEFAULT_LANG][key] ?? key;

  if (str.includes(" | ") && vars && typeof vars.n === "number") {
    const [singular, plural] = str.split(" | ");
    str = vars.n === 1 ? singular : plural;
  }

  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replaceAll(`{${k}}`, v);
    }
  }
  return str;
}


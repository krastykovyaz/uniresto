// Restopolis vocabularies that can be translated with real confidence
// (see CATEGORY_LABELS / ALLERGEN_LABELS below): category headers (a
// fixed list of ~25 strings, identical across both restaurants) and the
// 14 EU-regulation allergen names. What's NEVER translated is arbitrary
// free text Restopolis wrote itself -- dish names, descriptions, and an
// allergen's dish-specific "detail" (e.g. which cereal exactly) -- since
// there's no fixed vocabulary to translate against and a wrong guess on
// free text is a real risk, not just a cosmetic one, for an allergen
// context. See README.md Part 5 for the full rationale.
//
// Language list: the 10 most-spoken languages worldwide by total
// speakers (native + second-language), a commonly cited ranking (e.g.
// Ethnologue/Berlitz-style lists) -- not specific to this university's
// enrollment, since no such enrollment breakdown was available to go on
// -- plus Luxembourgish, the local language of the campus itself.

